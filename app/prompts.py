EXTRACT_FACTS_PROMPT = """\
Проанализируй последнее сообщение пользователя и извлеки важные \
долговременные факты, которые пригодятся в будущих диалогах.

Сохраняй только явно сообщённые пользователем факты. Не делай предположений, \
не делай медицинских или психологических выводов.

Что нужно сохранять (каждый факт отдельно, атомарно):
- аллергии и медицинские ограничения;
- пищевые ограничения;
- устойчивые предпочтения;
- место проживания;
- профессию;
- цели;
- интересы;
- проекты;
- предпочитаемый стиль общения.

Что НЕ нужно сохранять:
- приветствия, одноразовые вопросы, просьбы продолжить, случайные фразы;
- временное настроение;
- полный текст сообщения;
- ответы ассистента как факты о пользователе;
- предположения модели;
- пароли, токены, платёжные данные.

Один факт — один объект. Если важных фактов нет, верни пустой массив.

Для аллергий, лекарств, противопоказаний и строгих ограничений \
устанавливай critical=true.

Верни ТОЛЬКО валидный JSON в формате:
{{
  "memories": [
    {{
      "action": "add",
      "fact": "У пользователя аллергия на арахис",
      "category": "allergy",
      "importance": 1.0,
      "confidence": 1.0,
      "critical": true
    }}
  ]
}}

Допустимые action: add, update, delete, none.
Допустимые category: allergy, health, medication, dietary_restriction, \
identity, location, profession, preference, goal, education, project, other.

Сообщение пользователя:
{user_message}

Верни только JSON, без пояснений и без markdown-обёртки.\
"""


